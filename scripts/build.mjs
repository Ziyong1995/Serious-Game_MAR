import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import vm from 'node:vm';
const root=resolve(fileURLToPath(new URL('..',import.meta.url)));
const read=p=>readFile(resolve(root,p),'utf8');
const original=await read('src/game.html'),script=original.match(/<script>([\s\S]*?)<\/script>/)?.[1];
if(!script||!script.includes("v:3,")||!script.includes('function drawEvent()'))throw Error('This builder expects the supplied Watershed Council v3 HTML.');
const {version: release}=JSON.parse(await read('package.json'));
const engineEnd=script.indexOf('/* ===================== PERSISTENCE');
const clientEnd=script.indexOf('/* ===================== EVENTS =====================');
if(engineEnd<0 || clientEnd<engineEnd) throw Error('Missing game engine or browser event boundary.');
function replaceOnce(text,from,to){if(!text.includes(from))throw Error('Missing source marker: '+from);return text.replace(from,()=>to);}
const engineCore=script.slice(0,engineEnd);
const factory=`function makeEngine(){\n${engineCore}\nfunction save(){}\nfunction toast(){}\n${await read('src/engine-actions.txt')}\n}`;
let client=script.slice(0,clientEnd);
client=replaceOnce(client,'function renderDesk(){','function renderDesk(){\n  const currentTurnId=NET.currentTurnId;');
client=replaceOnce(client,"  const tabs=[['build'", "  if(NET.room && (NET.me!==currentTurnId || G.phase!=='turn')) return `<div class=\"desk\">${left}${waitingPanel()}</div>`;\n  const tabs=[['build'");
client=replaceOnce(client,'The other player confirms on this device.','The other player confirms on their own device.');
client=replaceOnce(client,
  'both owners get its full flood protection and ecology, and split its water.',
  'both owners get its full flood protection and split its water benefits. The host receives any odd unit. Shared infiltration gains +1 W.');
client=replaceOnce(client,"function save(){ try{ localStorage.setItem(KEY, JSON.stringify(G)); }catch(e){} }",'function save(){}');
const controller=await read('src/online-client.js');
const releaseDeclaration=`const RELEASE = ${JSON.stringify(release)};\n`;
const browser=`${releaseDeclaration}${client}\n${controller}`;
new vm.Script(browser,{filename:'online-game.js'});
const page=original.replace(/<script>[\s\S]*?<\/script>/,()=>`<script>\n${browser}\n</script>`)
  .replace('</style>',`${await read('src/online.css')}\n</style>`)
  .replace('<title>Watershed Council</title>',`<title>Watershed Council · Online v${release}</title>`);
const worker=`// Generated by npm run build. Edit src/game.html for game content, then rebuild.\n${releaseDeclaration}const PAGE=${JSON.stringify(page)};\n${factory}\n${await read('src/api.js')}\nexport {makeEngine, RELEASE as release};\n`;
await writeFile(resolve(root,'game-worker.mjs'),worker);
const check=spawnSync(process.execPath,['--check',resolve(root,'game-worker.mjs')],{encoding:'utf8'});if(check.status!==0)throw Error(check.stderr);
await writeFile(resolve(root,'version.json'),JSON.stringify({
  gameVersion:3, release, sourceFile:'src/game.html',
  sourceSha256:createHash('sha256').update(original).digest('hex'),
  eventDeck:34, playerSeats:[3,4,5], spectators:true
},null,2)+'\n');
console.log(`Built Watershed Council Online ${release}.`);
